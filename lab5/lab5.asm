ORG 0x1F3

INDEX: WORD 5A1
MODE: WORD 0x0
MASK: WORD 0xFF

WAIT:
	IN 3
	AND #0x40
	BEQ WAIT 

CHECK_MODE:
	LD MODE
	BEQ FIRST_WORD

SECOND_WORD:
	CLA
	ST MODE
	LD (INDEX)+
	AND MASK
	CALL OUTPUT
	JUMP WAIT
	
FIRST_WORD:
	INC
	ST MODE
	LD (INDEX)
	SWAB
	AND MASK
	CALL OUTPUT
	JUMP WAIT

OUTPUT:
	OUT 2
	CALL CHECK_SYMBOL
	RET

CHECK_SYMBOL:
	BEQ HALT
	RET

HALT:
	HLT

